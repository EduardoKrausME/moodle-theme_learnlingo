namespace theme_learnlingo;

use core\event\base;

/**
 * Refresh the public catalogue without touching per-visitor data.
 */
final class observer {
    /**
     * @param base $event Triggering event.
     * @return void
     */
    public static function public_courses_changed(base $event): void {
        homepage_context::purge_public_cache();
    }
}
